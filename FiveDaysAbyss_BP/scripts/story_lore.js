export async function showNote(player, index) {
  if (!alive(player)) return;
  const page = notes()[Math.max(0, Math.min(notes().length - 1, index | 0))];
  const form = new ActionFormData().title(page.title).body(page.body).button("Закрыть записку");
  try { await form.show(player); } catch (e) {
    try { player.sendMessage("§7" + page.body.split("\n").slice(0, 4).join(" ")); } catch (e2) {}
  }
}

