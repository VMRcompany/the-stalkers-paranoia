let cursor = 0;

export function initPsych() {
  Bus.on("second", () => {
    const gap = Math.max(35, 110 - intensity() * 18 - realDay() * 4);
    if ((Date.now() / 1000 | 0) % gap !== 0) return;
    const list = players().filter(alive);
    if (!list.length) return;
    const p = list[Math.floor(Math.random() * list.length)];
    cursor = (cursor + 1) % LINES.length;
    let line = LINES[cursor];
    if (gameDayNumber() >= 3 && Math.random() < 0.4) line = LINES[(cursor + 7) % LINES.length];
    sayCold(`${cleanName(p.name)}. ${line}`);
    if (isNight() || realDay() >= 3) whisper(p);
    if (Math.random() < 0.25) ask(p.name);
  });
}
